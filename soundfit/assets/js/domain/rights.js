/** Provenance / audit record attached to every delivery. */
export function buildProvenance({
  projectId, spec, score, runs, similarity, humanContributions, adapters, voiceMode = MVP_VOICE_MODE, locale = 'ko',
}) {
  return {
    id: `prov_${Date.now().toString(36)}`,
    schema: 'soundfit.provenance/1.1',
    projectId,
    createdAt: new Date().toISOString(),
    disclosure: {
      aiGenerated: true,
      text: {
        ko: '이 오디오는 AI로 생성되었습니다. 보컬은 합성 음성이며 실제 인물의 목소리가 아닙니다.',
        en: 'This audio was generated by AI. The vocal is synthetic and is not a real person\'s voice.',
      }[locale],
      basis: ['EU AI Act Art. 50 transparency (machine-readable marking + disclosure)', 'Platform policy ' + POLICY_VERSION],
    },
    generation: {
      specId: spec.id,
      specVersion: spec.specVersion,
      seed: spec.seed,
      genre: spec.genre,
      key: `${spec.key.tonic} ${spec.key.mode}`,
      tempo: spec.tempo,
      templateId: score?.templateId,
      sectionCount: score?.sections?.length,
      durationSeconds: score ? +score.duration.toFixed(2) : null,
      variation: spec.variation,
      revisionHistory: spec.revisionHistory || [],
    },
    adapters,
    voice: { mode: voiceMode, clonesRealPerson: false },
    similarity,
    humanContributions,
    runs,
  };
}
