/**
 * rights.js — request screening, voice policy, licence issuance, provenance.
 *
 * Design choice worth noting: screening is *pattern-based on the request intent*,
 * not based on a list of famous names. A name list is unmaintainable, leaks
 * policy, and fails outside its locale. Detecting "sing like <X>" / "same voice
 * as <X>" catches the behaviour we actually need to refuse, and lets us convert
 * the request into permitted musical attributes instead of dead-ending the user.
 */

export const POLICY_VERSION = '2026-08-01';

const IMPERSONATION_PATTERNS = [
  { id: 'voice_like_person', re: /([가-힣A-Za-z][가-힣A-Za-z0-9 .]{1,24})\s*(처럼|같은|같이|스타일로|톤으로)\s*(불러|노래|목소리|보컬|부르)/, severity: 'transform' },
  { id: 'voice_of_person', re: /([가-힣A-Za-z][가-힣A-Za-z0-9 .]{1,24})\s*(의)?\s*(목소리|음색|보컬)\s*(로|으로|같게|그대로)?/, severity: 'transform' },
  { id: 'voice_like_person_en', re: /\b(sing|sound|voice)\s+(like|as)\s+([A-Z][A-Za-z.'-]+(\s+[A-Z][A-Za-z.'-]+)?)/, severity: 'transform' },
  { id: 'clone_voice', re: /(목소리|voice)\s*(복제|클로닝|클론|clone|cloning)/i, severity: 'block' },
  { id: 'exact_copy', re: /(그대로|똑같이|동일하게|카피|표절|copy exactly|same as the original|1:1)/, severity: 'block' },
  { id: 'deceased_voice', re: /(돌아가신|고인|세상을 떠난|하늘에 계신|deceased|late)\s*.{0,12}(목소리|voice|음성)/, severity: 'block' },
  { id: 'song_replica', re: /(이 곡|그 노래|that song|this track)\s*.{0,10}(그대로|똑같|replicate|recreate)/, severity: 'block' },
];

/** Musical attributes we *can* honour when someone names a reference. */
const ATTRIBUTE_SUGGESTIONS = [
  { id: 'tempo', ko: '비슷한 템포 범위', en: 'comparable tempo range' },
  { id: 'instrumentation', ko: '악기 구성', en: 'instrumentation' },
  { id: 'era', ko: '시대적 사운드(믹스 성향)', en: 'era-style production' },
  { id: 'mood', ko: '정서와 분위기', en: 'mood and emotional register' },
  { id: 'vocal_texture', ko: '보컬 결(성별·음역·질감)', en: 'vocal texture (range, timbre class)' },
];

/**
 * @returns {{decision:'allow'|'transform'|'block', findings:Array, suggestedAttributes:Array, userMessage:object}}
 */
export function screenRequest(text, { locale = 'ko' } = {}) {
  const findings = [];
  const src = text || '';
  for (const p of IMPERSONATION_PATTERNS) {
    const m = p.re.exec(src);
    if (m) {
      findings.push({
        id: p.id,
        severity: p.severity,
        matched: m[0].slice(0, 60),
        subject: (m[1] || m[3] || '').trim().slice(0, 30),
      });
    }
  }
  const blocked = findings.find((f) => f.severity === 'block');
  const transform = findings.find((f) => f.severity === 'transform');
  const decision = blocked ? 'block' : transform ? 'transform' : 'allow';

  const messages = {
    block: {
      ko: '특정 인물의 목소리를 복제하거나 기존 곡을 그대로 재현하는 요청은 처리할 수 없습니다. 대신 원하시는 분위기·템포·악기 구성으로 바꿔 진행할 수 있어요.',
      en: 'We cannot clone a specific person\'s voice or reproduce an existing track. We can work from mood, tempo and instrumentation instead.',
    },
    transform: {
      ko: '특정 인물처럼 들리게 만들 수는 없어요. 대신 아래 음악적 속성으로 변환해서 반영합니다.',
      en: 'We cannot make it sound like a specific person. We will convert the request into the musical attributes below.',
    },
    allow: { ko: '', en: '' },
  };

  return {
    decision,
    findings,
    policyVersion: POLICY_VERSION,
    suggestedAttributes: decision === 'allow' ? [] : ATTRIBUTE_SUGGESTIONS,
    userMessage: messages[decision],
  };
}

