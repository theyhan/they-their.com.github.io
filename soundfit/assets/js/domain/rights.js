/**
 * Gate for any voice request. Returns the controls that would have to exist
 * before the mode could be enabled — this is the checklist v1.0 §15 described
 * in prose.
 */
export function checkVoiceRequest({ mode, occasion, consent }) {
  const m = VOICE_MODES[mode];
  if (!m) return { allowed: false, reason: 'unknown_voice_mode' };
  if (!m.availableInMvp) {
    return {
      allowed: false,
      reason: 'not_available_in_mvp',
      requiredControls: [
        'purpose-specific written consent from the voice subject',
        'identity + liveness verification of the subject',
        'consent scope: personal/commercial, territory, duration, sharing',
        'subject-initiated revocation endpoint and downstream takedown policy',
        'separate encryption boundary and access log for voice-derived assets',
        'provenance metadata + AI disclosure on every output',
      ],
      message: {
        ko: '이 모드는 MVP에서 제공하지 않습니다. 동의·신원확인 체계가 갖춰진 뒤 활성화됩니다.',
        en: 'This mode is disabled in the MVP until consent and identity verification are in place.',
      },
    };
  }
  if (m.prohibitedFor && m.prohibitedFor.includes(occasion)) {
    return { allowed: false, reason: 'prohibited_for_occasion' };
  }
  if (m.requiresConsent && !consent) return { allowed: false, reason: 'consent_missing' };
  return { allowed: true, mode: m, disclosure: m.disclosure };
}

